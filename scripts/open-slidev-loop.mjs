#!/usr/bin/env node

import { createServer } from "node:http";
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const outlinePath = path.join(root, "outline.json");
const slidesPath = path.join(root, "slides.md");
const registryPath = path.join(root, "registry.json");

function parseArgs(argv) {
  const [command, ...rest] = argv;
  const args = {};
  for (let i = 0; i < rest.length; i += 1) {
    const token = rest[i];
    if (!token.startsWith("--")) {
      continue;
    }
    const key = token.slice(2);
    const next = rest[i + 1];
    if (!next || next.startsWith("--")) {
      args[key] = true;
    } else {
      args[key] = next;
      i += 1;
    }
  }
  return { command, args };
}

async function readJson(filePath, fallback) {
  if (!existsSync(filePath)) {
    return fallback;
  }
  return JSON.parse(await readFile(filePath, "utf8"));
}

async function writeJson(filePath, value) {
  await writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

function requireString(value, label) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${label} must be a non-empty string`);
  }
}

function validateOutline(outline) {
  requireString(outline.project_id, "project_id");
  requireString(outline.title, "title");
  if (!Array.isArray(outline.slides) || outline.slides.length === 0) {
    throw new Error("slides must be a non-empty array");
  }
  const ids = new Set();
  for (const [index, slide] of outline.slides.entries()) {
    requireString(slide.id, `slides[${index}].id`);
    requireString(slide.title, `slides[${index}].title`);
    requireString(slide.summary, `slides[${index}].summary`);
    if (ids.has(slide.id)) {
      throw new Error(`duplicate slide id: ${slide.id}`);
    }
    ids.add(slide.id);
  }
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function renderFrontmatter(outline) {
  return [
    "---",
    "theme: default",
    `title: ${JSON.stringify(outline.title)}`,
    "info: |",
    `  ${outline.subtitle || "Generated by the open Slidev loop."}`,
    "drawings:",
    "  persist: false",
    "transition: slide-left",
    "mdc: true",
    "---",
    "",
  ].join("\n");
}

function renderCover(outline, slide) {
  return [
    `# ${slide.title}`,
    "",
    `<div class="open-loop-subtitle">${escapeHtml(outline.subtitle || slide.summary)}</div>`,
    "",
    `<div class="open-loop-meta">${escapeHtml(outline.author || "AI Slide System")} · ${escapeHtml(outline.date || "")}</div>`,
    "",
    `<!-- ${slide.summary} -->`,
  ].join("\n");
}

function renderBullets(slide) {
  const bullets = Array.isArray(slide.bullets) ? slide.bullets : [slide.summary];
  return [
    `# ${slide.title}`,
    "",
    `<div class="open-loop-summary">${escapeHtml(slide.summary)}</div>`,
    "",
    ...bullets.map((item) => `- ${item}`),
  ].join("\n");
}

function renderMermaid(slide) {
  return [
    `# ${slide.title}`,
    "",
    slide.summary,
    "",
    "```mermaid",
    slide.diagram || "flowchart LR\n  A[Outline] --> B[Slides]",
    "```",
  ].join("\n");
}

function renderTable(slide) {
  const headers = Array.isArray(slide.headers) ? slide.headers : ["字段", "说明"];
  const rows = Array.isArray(slide.rows) ? slide.rows : [];
  return [
    `# ${slide.title}`,
    "",
    slide.summary,
    "",
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function renderSlide(outline, slide, index) {
  const body = {
    cover: () => renderCover(outline, slide),
    bullets: () => renderBullets(slide),
    mermaid: () => renderMermaid(slide),
    table: () => renderTable(slide),
  }[slide.layout || "bullets"]?.() || renderBullets(slide);

  const note = [
    "",
    "<!--",
    `Slide ${index + 1}: ${slide.summary}`,
    "-->",
  ].join("\n");

  return `${body}${note}`;
}

function renderStyles(outline) {
  const accent = outline.style?.accent || "#2563eb";
  const secondary = outline.style?.secondary || "#16a34a";
  const background = outline.style?.background || "#f8fafc";
  return [
    "<style>",
    ":root {",
    `  --open-loop-accent: ${accent};`,
    `  --open-loop-secondary: ${secondary};`,
    `  --open-loop-background: ${background};`,
    "}",
    ".slidev-layout { background: var(--open-loop-background); }",
    ".slidev-layout h1 { color: #0f172a; letter-spacing: 0; }",
    ".open-loop-subtitle { font-size: 1.6rem; line-height: 1.35; color: var(--open-loop-accent); margin-top: 1rem; max-width: 820px; }",
    ".open-loop-meta { margin-top: 2rem; color: #475569; font-size: 1rem; }",
    ".open-loop-summary { color: #475569; margin: 0.5rem 0 1.25rem; font-size: 1.1rem; }",
    ".slidev-layout li { margin: 0.55rem 0; }",
    ".slidev-layout table { font-size: 0.95rem; }",
    ".slidev-layout th { color: white; background: var(--open-loop-accent); }",
    ".slidev-layout td { background: rgba(255,255,255,0.72); }",
    "</style>",
  ].join("\n");
}

async function updateRegistry(project, patch) {
  const registry = await readJson(registryPath, { projects: {} });
  registry.projects[project.project_id] = {
    ...(registry.projects[project.project_id] || {}),
    project_id: project.project_id,
    runtime: "slidev",
    project_dir: root,
    entry: "slides.md",
    updated_at: new Date().toISOString(),
    ...patch,
  };
  await writeJson(registryPath, registry);
}

async function generate() {
  const outline = await readJson(outlinePath);
  validateOutline(outline);
  const slideBodies = outline.slides.map((slide, index) => renderSlide(outline, slide, index));
  slideBodies[slideBodies.length - 1] = `${slideBodies[slideBodies.length - 1]}\n\n${renderStyles(outline)}`;
  const slides = `${renderFrontmatter(outline)}${slideBodies.join("\n\n---\n\n")}`;

  await writeFile(slidesPath, `${slides}\n`);
  await updateRegistry(outline, {
    status: "generated",
    slide_count: outline.slides.length,
  });
  console.log(`generated ${path.relative(root, slidesPath)}`);
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    stdio: options.capture ? "pipe" : "inherit",
    encoding: "utf8",
  });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed${result.stderr ? `\n${result.stderr}` : ""}`);
  }
  return result;
}

async function present(args) {
  const outline = await readJson(outlinePath);
  validateOutline(outline);
  run("npm", ["run", "build"]);
  const distDir = path.join(root, "dist");
  if (!existsSync(path.join(distDir, "index.html"))) {
    throw new Error("dist/index.html was not produced");
  }

  const port = Number(args.port || 4185);
  const url = args.serve ? `http://localhost:${port}/` : null;
  await updateRegistry(outline, {
    status: args.serve ? "serving" : "built",
    dist_dir: distDir,
    preview_url: url,
  });

  const payload = {
    project_id: outline.project_id,
    mode: args.serve ? "static-server" : "static-dist",
    dist_dir: distDir,
    preview_url: url,
  };
  console.log(JSON.stringify(payload, null, 2));

  if (args.serve) {
    await serve(distDir, port);
  }
}

async function serve(rootDir, port) {
  const server = createServer(async (req, res) => {
    try {
      const url = new URL(req.url || "/", `http://localhost:${port}`);
      const requested = decodeURIComponent(url.pathname);
      const clean = path.normalize(requested).replace(/^(\.\.[/\\])+/, "");
      let filePath = path.join(rootDir, clean);
      if (requested.endsWith("/")) {
        filePath = path.join(filePath, "index.html");
      }
      if (!existsSync(filePath) || (await stat(filePath)).isDirectory()) {
        filePath = path.join(rootDir, "index.html");
      }
      const type = {
        ".html": "text/html; charset=utf-8",
        ".js": "text/javascript; charset=utf-8",
        ".css": "text/css; charset=utf-8",
        ".png": "image/png",
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".svg": "image/svg+xml",
        ".webp": "image/webp",
      }[path.extname(filePath)] || "application/octet-stream";
      res.writeHead(200, { "content-type": type });
      res.end(await readFile(filePath));
    } catch (error) {
      res.writeHead(500, { "content-type": "text/plain; charset=utf-8" });
      res.end(String(error?.stack || error));
    }
  });
  server.listen(port, "localhost", () => {
    console.log(`open-slidev-loop serving ${rootDir}`);
    console.log(`preview url: http://localhost:${port}/`);
  });
}

function countSlideSeparators(source) {
  const withoutFrontmatter = source.replace(/^---[\s\S]*?\n---\n+/, "");
  if (!withoutFrontmatter.trim()) {
    return 0;
  }
  return withoutFrontmatter.split(/\n---\n/g).length;
}

async function verify() {
  const outline = await readJson(outlinePath);
  validateOutline(outline);
  const registry = await readJson(registryPath, { projects: {} });
  const slidesSource = existsSync(slidesPath) ? await readFile(slidesPath, "utf8") : "";
  const project = registry.projects[outline.project_id] || null;
  const distIndex = path.join(root, "dist", "index.html");
  const pngDir = path.join(root, "exports", "png");
  const pngCount = existsSync(pngDir)
    ? (await import("node:fs/promises")).readdir(pngDir).then((files) => files.filter((file) => file.endsWith(".png")).length)
    : 0;
  const report = {
    project_id: outline.project_id,
    outline_slide_count: outline.slides.length,
    generated_slides_md: existsSync(slidesPath),
    slide_separator_count: slidesSource ? countSlideSeparators(slidesSource) : 0,
    dist_exists: existsSync(distIndex),
    registry_has_project: Boolean(project),
    registry_status: project?.status || null,
    exports: {
      png_count: await pngCount,
      pdf_exists: existsSync(path.join(root, "exports", "deck.pdf")),
      pptx_exists: existsSync(path.join(root, "exports", "deck.pptx")),
    },
    checks: [],
  };
  report.checks.push({
    name: "outline/slides.md generated",
    ok: report.generated_slides_md,
  });
  report.checks.push({
    name: "registry project registered",
    ok: report.registry_has_project,
  });
  report.checks.push({
    name: "dist build exists",
    ok: report.dist_exists,
  });
  report.ok = report.checks.every((check) => check.ok);
  await updateRegistry(outline, {
    status: report.ok ? "verified" : "needs_attention",
    exports: {
      png_dir: existsSync(pngDir) ? pngDir : null,
      pdf: report.exports.pdf_exists ? path.join(root, "exports", "deck.pdf") : null,
      pptx: report.exports.pptx_exists ? path.join(root, "exports", "deck.pptx") : null,
      verify_report: path.join(root, "exports", "verify-report.json"),
    },
  });
  await mkdir(path.join(root, "exports"), { recursive: true });
  await writeJson(path.join(root, "exports", "verify-report.json"), report);
  console.log(JSON.stringify(report, null, 2));
}

async function main() {
  const { command, args } = parseArgs(process.argv.slice(2));
  if (command === "generate") {
    await generate();
  } else if (command === "present") {
    await present(args);
  } else if (command === "verify") {
    await verify();
  } else {
    console.error("Usage:");
    console.error("  node scripts/open-slidev-loop.mjs generate");
    console.error("  node scripts/open-slidev-loop.mjs present [--serve --port 4185]");
    console.error("  node scripts/open-slidev-loop.mjs verify");
    process.exit(2);
  }
}

main().catch((error) => {
  console.error(error?.stack || error);
  process.exit(1);
});
